-- the constraint allows now (other changes extend it too).
DO $$
DECLARE def text;
BEGIN
 SELECT pg_get_constraintdef(oid) INTO def FROM pg_constraint WHERE conname='task_alerts_kind_check' AND conrelid='task_alerts'::regclass;
 IF def IS NOT NULL AND position('comment_unhandled' in def)=0 THEN
  ALTER TABLE task_alerts DROP CONSTRAINT task_alerts_kind_check;
  EXECUTE 'ALTER TABLE task_alerts ADD CONSTRAINT task_alerts_kind_check ' || replace(def, 'ARRAY[', 'ARRAY[''comment_unhandled''::text, ');
 END IF;
END $$;
