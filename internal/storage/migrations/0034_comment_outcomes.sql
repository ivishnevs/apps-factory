-- Owner comments handled (owner-comments-handled): every board comment on a task gets an outcome. A row is one
-- obligation to give that outcome: the task's runs for the comment itself (reason assignee: whoever runs the
-- task next), a manager's conversation task for a forward, the project lead's conversation task when it is
-- woken (declined, stalled, locked). Every exit of a run of task_id is refused while a row of task_id is open.
-- shown_run is the last run shown the comment; missed counts runs that ended without an exit after being shown
-- it (counted_run guards a run counted twice); a second miss raises an alert to the owner.
CREATE TABLE comment_outcomes (
 id text NOT NULL,
 company_id text NOT NULL REFERENCES companies(id),
 comment_id text NOT NULL,
 task_id text NOT NULL,
 agent text NOT NULL,
 reason text NOT NULL,
 status text NOT NULL DEFAULT 'open',
 note text NOT NULL DEFAULT '',
 forwarded_to text NOT NULL DEFAULT '',
 linked_task text NOT NULL DEFAULT '',
 shown_run text NOT NULL DEFAULT '',
 counted_run text NOT NULL DEFAULT '',
 missed integer NOT NULL DEFAULT 0,
 created_at bigint NOT NULL,
 decided_at bigint NOT NULL DEFAULT 0,
 seq bigint GENERATED BY DEFAULT AS IDENTITY,
 PRIMARY KEY (company_id, id),
 UNIQUE (id),
 UNIQUE (company_id, comment_id, task_id),
 FOREIGN KEY (company_id, comment_id) REFERENCES task_comments(company_id, id),
 FOREIGN KEY (company_id, task_id) REFERENCES tasks(company_id, id)
);
CREATE INDEX comment_outcomes_open ON comment_outcomes(company_id, task_id) WHERE status='open';
CREATE INDEX comment_outcomes_comment ON comment_outcomes(company_id, comment_id, seq);

-- A locked category (release, money, deletion, legal) named by the owner or detected in the text: the project
-- lead is woken at once.
