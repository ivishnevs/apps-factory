-- Structured catalog (structured-catalog, step 1): one row per configuration entity with its parsed spec and the
-- document it renders to, and an append-only change log for history and undo. Core still reads catalog_documents;
-- companies switch over once their entities render the same catalog (config_hash per agent).
CREATE TABLE catalog_entities (
 company_id text NOT NULL REFERENCES companies(id),
 kind text NOT NULL,
 name text NOT NULL,
 path text NOT NULL,
 title text NOT NULL DEFAULT '',
 spec jsonb NOT NULL DEFAULT '{}',
 content text NOT NULL,
 row_version bigint NOT NULL DEFAULT 1,
 updated_at bigint NOT NULL,
 updated_by text NOT NULL,
 PRIMARY KEY (company_id, kind, name),
 UNIQUE (company_id, path)
);
CREATE TABLE catalog_changes (
 company_id text NOT NULL REFERENCES companies(id),
 seq bigint GENERATED BY DEFAULT AS IDENTITY,
 at bigint NOT NULL,
 author text NOT NULL,
 person text NOT NULL DEFAULT '',
 note text NOT NULL DEFAULT '',
 changes jsonb NOT NULL,
 PRIMARY KEY (company_id, seq)
);
ALTER TABLE companies ADD COLUMN catalog_source text NOT NULL DEFAULT 'documents';
