-- Baseline schema (postgres-tenancy D2, D5): the whole schema up to hierarchy, on Postgres, with accounts,
-- users, companies and memberships. Every domain table carries company_id; every foreign key includes it, so a
-- row can never reference another company's row. Row IDs stay globally unique (UNIQUE(id) next to the
-- composite key), so a lookup by a Core-issued ID cannot reach another company. Times are Unix seconds;
-- 0/1 flags stay integers. Entity documents are json (kept as written); seq columns give the insertion order.

CREATE TABLE core_meta (
 key text PRIMARY KEY,
 value text NOT NULL
);

