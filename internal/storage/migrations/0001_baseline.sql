-- A run's status is its phase (reliable-recovery D1); an ENDED run has an outcome.
CREATE FUNCTION run_phase() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status NOT IN ('QUEUED','CLAIMED','RUNNING','CANCELLING','ENDED') OR (NEW.status='ENDED' AND NEW.outcome='') THEN
  RAISE EXCEPTION 'run status must be a phase; an ENDED run needs its outcome' USING ERRCODE = 'check_violation';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER run_phase BEFORE UPDATE OF status ON runs FOR EACH ROW EXECUTE FUNCTION run_phase();

