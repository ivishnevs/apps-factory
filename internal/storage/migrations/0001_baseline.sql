-- usage_list is runs.usage as a JSON array; anything else (empty, invalid) is an empty list.
CREATE FUNCTION usage_list(u text) RETURNS jsonb LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE v jsonb;
BEGIN
 IF u IS NULL OR u = '' THEN RETURN '[]'::jsonb; END IF;
 v := u::jsonb;
 IF jsonb_typeof(v) <> 'array' THEN RETURN '[]'::jsonb; END IF;
 RETURN v;
EXCEPTION WHEN others THEN
 RETURN '[]'::jsonb;
END $$;

CREATE VIEW run_cost_source AS
SELECT r.company_id AS company_id, r.id AS run_id, coalesce(r.task_id,'') AS task_id, coalesce(r.spec->>'project','') AS project_id,
 r.agent AS agent, coalesce(r.spec->>'provider','') AS provider,
 coalesce((SELECT u->>'model' FROM jsonb_array_elements(usage_list(r.usage)) u
  ORDER BY coalesce((u->>'input')::numeric,0)+coalesce((u->>'output')::numeric,0) DESC LIMIT 1),
  coalesce(r.spec#>>'{runtime_options,model}','')) AS model,
 r.outcome AS outcome,
 coalesce((SELECT sum(coalesce((u->>'input')::numeric,0)) FROM jsonb_array_elements(usage_list(r.usage)) u),0)::bigint AS input_tokens,
 coalesce((SELECT sum(coalesce((u->>'output')::numeric,0)) FROM jsonb_array_elements(usage_list(r.usage)) u),0)::bigint AS output_tokens,
 coalesce((SELECT sum(coalesce((u->>'cache_read')::numeric,0)) FROM jsonb_array_elements(usage_list(r.usage)) u),0)::bigint AS cache_read_tokens,
 coalesce((SELECT sum(coalesce((u->>'cache_write')::numeric,0)) FROM jsonb_array_elements(usage_list(r.usage)) u),0)::bigint AS cache_write_tokens,
 coalesce(r.finished_at,0) AS finished_at
FROM runs r;

CREATE FUNCTION run_cost_ended() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO run_costs(company_id,run_id,task_id,project_id,agent,provider,model,outcome,input_tokens,output_tokens,cache_read_tokens,cache_write_tokens,recorded_at)
  SELECT company_id,run_id,task_id,project_id,agent,provider,model,outcome,input_tokens,output_tokens,cache_read_tokens,cache_write_tokens,
   CASE WHEN finished_at>0 THEN finished_at ELSE extract(epoch FROM now())::bigint END FROM run_cost_source WHERE run_id=NEW.id
 ON CONFLICT (run_id) DO UPDATE SET outcome=excluded.outcome,model=excluded.model,input_tokens=excluded.input_tokens,output_tokens=excluded.output_tokens,
  cache_read_tokens=excluded.cache_read_tokens,cache_write_tokens=excluded.cache_write_tokens,priced=0;
 RETURN NULL;
END $$;
CREATE TRIGGER run_cost_ended AFTER UPDATE OF status ON runs FOR EACH ROW
 WHEN (NEW.status='ENDED' AND OLD.status<>'ENDED') EXECUTE FUNCTION run_cost_ended();

CREATE FUNCTION run_cost_late() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE run_costs SET (outcome,model,input_tokens,output_tokens,cache_read_tokens,cache_write_tokens,priced)=
  (SELECT outcome,model,input_tokens,output_tokens,cache_read_tokens,cache_write_tokens,0 FROM run_cost_source WHERE run_id=NEW.id)
 WHERE run_id=NEW.id;
 RETURN NULL;
END $$;
CREATE TRIGGER run_cost_late AFTER UPDATE OF usage, outcome ON runs FOR EACH ROW
 WHEN (NEW.status='ENDED' AND OLD.status='ENDED') EXECUTE FUNCTION run_cost_late();
