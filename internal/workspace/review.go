// node-ties: a run of an agent that is not the task's implementer (a reviewer, QA, an accepting manager) works
// in a disposable copy checked out from the pushed head of the task branch. It never touches the implementer's
// worktree, is never sealed, cannot push (owner 2026-11-10: "this is a review copy; your result is the
// verdict") and is deleted after the run.

// NotReviewableError: the task branch has no pushed head, so there is nothing to review (local commits on some
// node are not the task's handed-over work).
type NotReviewableError struct{ Branch string }

func (e *NotReviewableError) Error() string {
	return fmt.Sprintf("not reviewable: the task branch %s has no pushed head on the remote; the implementer must push it (its exit) before it can be reviewed", e.Branch)
}

// ReviewRefusal is what the review copy's pre-push hook says.
const ReviewRefusal = "factory: this is a review copy; your result is the verdict"

// ValidCarry checks a project's workspace.review_carry entry (tasks.ValidReviewCarry).
func ValidCarry(p string) error { return tasks.ValidReviewCarry(p) }

// ReviewCopy creates the disposable worktree of a review run of r.Task: detached at origin/<task branch> as just
// fetched, with no push URL and a pre-push hook that refuses, and the project's carry directories (ignored by
// git, e.g. build caches) copied from the task's worktree on this node when it has one. Release stops the run's
// tracked process group and deletes the copy.
func (w *Worktrees) ReviewCopy(ctx context.Context, r Request, carry []string) (Worktree, error) {
	dir, err := w.project(r)
	if err != nil {
		return Worktree{}, err
	}
	if r.RepoURL == "" {
		return Worktree{}, errors.New("workspace: repo url is required")
	}
	branch := branchName(r)
	if _, err = git(ctx, "", nil, "check-ref-format", "--branch", branch); err != nil {
		return Worktree{}, fmt.Errorf("workspace: invalid branch %q", branch)
	}
	unlock, err := lockRepo(ctx, filepath.Join(dir, "repo.lock"))
	if err != nil {
		return Worktree{}, err
	}
	defer unlock()
	repo := filepath.Join(dir, "repo")
	if err = w.ensureClone(ctx, dir, repo, r.RepoURL); err != nil {
		return Worktree{}, err
	}
	if _, err = git(ctx, repo, nil, "fetch", "--prune", "origin"); err != nil {
		return Worktree{}, err
	}
	head, err := git(ctx, repo, nil, "rev-parse", "--verify", "--quiet", "refs/remotes/origin/"+branch+"^{commit}")
	if err != nil || head == "" {
		return Worktree{}, &NotReviewableError{Branch: branch}
	}
	if err = os.MkdirAll(filepath.Join(dir, "reviews"), 0o755); err != nil {
		return Worktree{}, err
	}
	path, err := os.MkdirTemp(filepath.Join(dir, "reviews"), r.Task+"-")
	if err != nil {
		return Worktree{}, err
	}
	scratch := path + ".scratch"
	remove := func() {
		_, _ = git(context.WithoutCancel(ctx), repo, nil, "worktree", "remove", "--force", "--force", path)
		_ = os.RemoveAll(path)
		_ = os.RemoveAll(scratch)
		_, _ = git(context.WithoutCancel(ctx), repo, nil, "worktree", "prune")
	}
	if err = os.Remove(path); err != nil { // git worktree add wants to create it
		return Worktree{}, err
	}
	if _, err = git(ctx, repo, nil, "worktree", "add", "--quiet", "--detach", path, head); err != nil {
		remove()
		return Worktree{}, err
	}
	hooks := filepath.Join(dir, "review-hooks")
	if err = writeFile(filepath.Join(hooks, "pre-push"), "#!/bin/sh\n# Generated by App Factory (node-ties): a review copy never pushes.\necho '"+ReviewRefusal+"' >&2\nexit 1\n", 0o755); err != nil {
		remove()
		return Worktree{}, err
	}
	for _, kv := range [][2]string{
		{"core.hooksPath", hooks},
		// No push URL: `git push` (origin) fails before it reaches the remote; a push to an explicit URL meets the hook.
		{"remote.origin.pushurl", "/dev/null/factory-review-copy-cannot-push"},
	} {
		if _, err = git(ctx, path, nil, "config", "--worktree", kv[0], kv[1]); err != nil {
			remove()
			return Worktree{}, err
		}
	}
	if err = gitexclude.Add(ctx, path, "/.factory/"); err != nil {
		remove()
		return Worktree{}, err
	}
	if err = os.MkdirAll(filepath.Join(path, ".factory"), 0o755); err != nil {
		remove()
		return Worktree{}, err
	}
	if err = os.MkdirAll(scratch, 0o755); err != nil {
		remove()
		return Worktree{}, err
	}
	carryInto(ctx, filepath.Join(dir, "tasks", r.Task), path, carry)
	wt := Worktree{Path: path, Scratch: scratch, Repo: repo}
	wt.Release = func() error {
		err := stopRun(path)
		if err != nil {
			return err // the group survived: the copy stays for the next start's cleanup
		}
		unlock, lerr := lockRepo(context.WithoutCancel(ctx), filepath.Join(dir, "repo.lock"))
		if lerr != nil {
			return lerr
		}
		defer unlock()
		remove()
		return nil
	}
	return wt, nil
}

// carryInto copies the listed directories from the task's worktree (src) into the review copy when git ignores
// them there: a carry entry never brings tracked files or anything else ignored (.env, keys, local config).
func carryInto(ctx context.Context, src, dst string, carry []string) {
	if len(carry) == 0 {
		return
	}
	if _, err := os.Stat(filepath.Join(src, ".factory", "state")); err != nil {
		return // no worktree of the task on this node
	}
	for _, c := range carry {
		if ValidCarry(c) != nil {
			continue
		}
		from := filepath.Join(src, filepath.Clean(c))
		info, err := os.Lstat(from)
		if err != nil || !info.IsDir() {
			continue
		}
		if _, err = git(ctx, src, nil, "check-ignore", "-q", "--", filepath.Clean(c)); err != nil {
			slog.Info("review_carry skipped: not ignored by git", "dir", c)
			continue
		}
		to := filepath.Join(dst, filepath.Clean(c))
		if err = os.MkdirAll(filepath.Dir(to), 0o755); err != nil {
			continue
		}
		_ = os.RemoveAll(to)
		if out, err := exec.CommandContext(ctx, "cp", "-a", from, to).CombinedOutput(); err != nil {
			slog.Warn("review_carry copy failed", "dir", c, "error", err, "output", strings.TrimSpace(string(out)))
		}
	}
}

func writeFile(p, s string, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	if b, err := os.ReadFile(p); err == nil && string(b) == s {
		return nil
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, []byte(s), mode); err != nil {
		return err
	}
	return os.Rename(tmp, p)
}

// RemoveReviewCopies deletes the review copies a previous node process left (their runs ended with it).
func (w *Worktrees) RemoveReviewCopies(ctx context.Context) error {
	paths, err := filepath.Glob(filepath.Join(w.root, "*", "*", "reviews", "*"))
	if err != nil {
		return err
	}
	var errs []error
	for _, p := range paths {
		if strings.HasSuffix(p, ".scratch") {
			_ = os.RemoveAll(p)
			continue
		}
		if err := stopRun(p); err != nil {
			errs = append(errs, err)
			continue
		}
		repo := filepath.Join(filepath.Dir(filepath.Dir(p)), "repo")
		_, _ = git(ctx, repo, nil, "worktree", "remove", "--force", "--force", p)
		if err := os.RemoveAll(p); err != nil {
			errs = append(errs, err)
		}
		_, _ = git(ctx, repo, nil, "worktree", "prune")
	}
	return errors.Join(errs...)
}
